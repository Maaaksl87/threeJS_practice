// Детермінований генератор випадкових чисел за числовим seed.
//
// Чому не Math.random(): усе «випадкове» в сцені має лишатися тим самим між
// перезапусками й hot-reload. Інакше вікно, яке щойно розгорілось, стрибало б
// на інший розклад через незв'язану правку коду, а зоряне небо перемальовувалось
// би від зміни в зовсім іншому файлі. Один і той самий seed — та сама картинка.
export function mulberry32(seed: number) {
  let a = seed | 0
  return function () {
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
